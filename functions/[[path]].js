// Cloudflare Pages Function (catch-all): markdown content negotiation for AI agents.
//
// - `Accept: text/markdown` serves the .md variant of a page (https://acceptmarkdown.com)
// - Negotiated responses carry `Vary: Accept, Accept-Encoding` so caches keep variants apart
// - Requests that accept neither text/html nor text/markdown are rejected with 406
// - q-values are honored per https://acceptmarkdown.com/guides/accept-parsing:
//   a lone `text/markdown;q=0` means "anything but markdown" (serve HTML), while an
//   Accept list of positive-q types that matches nothing we produce returns 406
// - HTML responses advertise their markdown twin via Link headers (https://llmstxt.org v2):
//   `rel="alternate"; type="text/markdown"` + `rel="describedby"` pointing at /llms.txt
// - Markdown-preferring agents that hit an unknown path get a markdown 404 body
//   with recovery links (llms.txt, sitemap, blog index).

const VARY = 'Accept, Accept-Encoding'

const MD_NOT_FOUND = `# 404 - Page not found

This page does not exist on Justart-dev Blog, a Korean-language personal development archive.

## Where to look next

- [Blog index](/blog.md) - all posts as markdown
- [Home](/index.md) - site overview as markdown
- [Sitemap](/sitemap.xml) - all pages
- [RSS feed](/feed.xml) - full-text feed
`

function parseAcceptEntries(header) {
  const entries = []
  if (!header) return entries
  for (const part of header.split(',')) {
    const [mediaRange, ...params] = part.trim().split(';')
    const type = mediaRange.trim().toLowerCase()
    if (!type) continue
    let q = 1
    for (const param of params) {
      const [key, value] = param.trim().split('=')
      if (key === 'q') {
        const parsed = parseFloat(value)
        if (!Number.isNaN(parsed)) q = parsed
      }
    }
    entries.push({ type, q })
  }
  return entries
}

function specificity(entry) {
  if (entry.type.includes('*')) return entry.type === '*/*' ? 0 : 1
  return 2
}

// Quality of `mediaType` under an Accept header. Returns 0 when the type is not
// acceptable. An Accept list made only of q=0 entries is an exclusion list:
// everything not excluded is acceptable (acceptmarkdown.com parsing guide).
function quality(entries, mediaType) {
  if (entries.length === 0) return 1 // missing/empty Accept: no constraint
  const type = mediaType.split('/')[0]
  let match = null
  for (const entry of entries) {
    if (entry.type === mediaType || entry.type === `${type}/*` || entry.type === '*/*') {
      if (!match || specificity(entry) > specificity(match)) match = entry
    }
  }
  if (match) return match.q
  const hasPositive = entries.some((entry) => entry.q > 0)
  return hasPositive ? 0 : 1
}

// Pages that have a markdown variant (generated by scripts/generate-markdown.mjs).
// All other extensionless paths serve HTML only.
function mdPathFor(pathname) {
  const p = pathname.replace(/\/+$/, '') || '/'
  if (p === '/') return '/index.md'
  if (p === '/blog') return `${p}.md`
  if (/^\/blog\/(?!page\/)[^/]+\/[^/]+$/.test(p)) return `${p}.md`
  return null
}

function mergeVary(headers) {
  const tokens = new Set(VARY.split(',').map((t) => t.trim().toLowerCase()))
  const existing = headers.get('Vary')
  if (existing) {
    for (const token of existing.split(',')) {
      const trimmed = token.trim().toLowerCase()
      if (trimmed && trimmed !== '*') tokens.add(trimmed)
    }
  }
  headers.set('Vary', [...tokens].join(', '))
  return headers
}

function mdResponse(body, status, extraHeaders = {}) {
  const headers = new Headers(extraHeaders)
  headers.set('Content-Type', 'text/markdown; charset=utf-8')
  mergeVary(headers)
  return new Response(body, { status, headers })
}

function htmlResponse(res, { link } = {}) {
  const headers = new Headers(res.headers)
  mergeVary(headers)
  if (link && res.status === 200) {
    headers.set(
      'Link',
      `<${link}>; rel="alternate"; type="text/markdown", </llms.txt>; rel="describedby"`
    )
  }
  return new Response(res.body, { status: res.status, headers })
}

function fetchHtmlAsset(request, env, url) {
  const headers = new Headers(request.headers)
  headers.set('accept', 'text/html')
  return env.ASSETS.fetch(new Request(url, { method: request.method, headers }))
}

function notAcceptable(request) {
  const body = `This resource is available in:
- text/html
- text/markdown

You requested: ${(request.headers.get('accept') || '(none)').slice(0, 120)}
`
  return new Response(body, {
    status: 406,
    headers: { 'Content-Type': 'text/plain; charset=utf-8', Vary: VARY },
  })
}

async function serveNotFound(request, env, url, preferMarkdown, htmlRes) {
  if (preferMarkdown) {
    return mdResponse(MD_NOT_FOUND, 404)
  }
  const contentType = htmlRes.headers.get('content-type') || ''
  if (!contentType.includes('text/html')) {
    // Asset serving answered with a bare 404: fall back to the custom 404 page.
    const custom = await env.ASSETS.fetch(new Request(new URL('/404.html', url.origin)))
    if (custom.status === 200) {
      const headers = new Headers(custom.headers)
      mergeVary(headers)
      return new Response(custom.body, { status: 404, headers })
    }
  }
  return htmlResponse(htmlRes)
}

export async function onRequest(context) {
  const { request, env } = context
  const url = new URL(request.url)
  const pathname = url.pathname

  // Framework-internal requests (RSC navigation) pass through untouched.
  if (
    request.headers.get('rsc') ||
    request.headers.get('next-router-prefetch') ||
    request.headers.get('next-router-state-tree')
  ) {
    return env.ASSETS.fetch(request)
  }

  // Only GET/HEAD participate in negotiation.
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    return env.ASSETS.fetch(request)
  }

  // Direct file requests (JS/CSS/images/xml/json/md/txt) pass through.
  const lastDot = pathname.lastIndexOf('.')
  const lastSlash = pathname.lastIndexOf('/')
  if (lastDot > lastSlash) {
    if (pathname.endsWith('.md')) {
      const res = await env.ASSETS.fetch(request)
      if (res.status !== 200) return res
      const headers = new Headers(res.headers)
      headers.set('Content-Type', 'text/markdown; charset=utf-8')
      return new Response(res.body, { status: 200, headers })
    }
    return env.ASSETS.fetch(request)
  }

  const entries = parseAcceptEntries(request.headers.get('accept'))
  const htmlQ = quality(entries, 'text/html')
  const mdQ = quality(entries, 'text/markdown')

  if (htmlQ <= 0 && mdQ <= 0) {
    return notAcceptable(request)
  }

  const preferMarkdown = mdQ > htmlQ
  const mdPath = mdPathFor(pathname)

  if (preferMarkdown) {
    if (mdPath) {
      const mdRes = await env.ASSETS.fetch(
        new Request(new URL(mdPath, url.origin), { method: 'GET' })
      )
      if (mdRes.status === 200) {
        return mdResponse(request.method === 'HEAD' ? null : mdRes.body, 200, {
          Link: '</llms.txt>; rel="describedby"',
        })
      }
    }
    // No markdown variant for this path: serve the HTML variant (still varies by Accept).
    const htmlRes = await fetchHtmlAsset(request, env, url)
    if (htmlRes.status === 404) {
      return serveNotFound(request, env, url, true, htmlRes)
    }
    return htmlResponse(htmlRes)
  }

  const htmlRes = await fetchHtmlAsset(request, env, url)
  if (htmlRes.status === 404) {
    return serveNotFound(request, env, url, false, htmlRes)
  }
  return htmlResponse(htmlRes, { link: mdPath })
}
